import os
import csv
import numpy as np

DOMAINS = [
    "ecology", "oncology", "econ", "battery", "pkpd", "synbio", "climate", "cardio", "bz_chem", "epidemiology",
    "neuro", "fluid", "astro", "chem_kinetics", "immune", "pop_genetics", "thermo", "materials", "agriculture", "social",
    "real_sunspots", "real_nile", "real_macro", "real_theophylline", "real_co2"
]

def format_loss(val):
    if val == float('inf') or np.isinf(val):
        return r"\infty"
    if val < 0.001:
        return f"{val:.2e}".replace("e-0", "e-").replace("e-", r"\times 10^{-") + "}"
    return f"{val:.4f}"

def main():
    print("Compiling results across all completed runs...")
    os.makedirs("paper", exist_ok=True)
    
    rows = []
    for d in DOMAINS:
        start_losses = []
        final_losses = []
        total_accepted = 0
        improving_runs = 0
        completed_runs = 0
        
        for r in range(1, 11):
            path = f"scheduler_logs/run_{r}/qwen36_27b_{d}_run_history.csv"
            if not os.path.exists(path):
                continue
            
            completed_runs += 1
            start_loss = None
            final_loss = None
            run_accepted = 0
            
            try:
                with open(path, "r") as f:
                    reader = csv.DictReader(f)
                    for row in reader:
                        loss = float(row["Baseline_Loss"])
                        if start_loss is None:
                            start_loss = loss
                        final_loss = loss
                        if row["Action"] == "ACCEPTED":
                            run_accepted += 1
                
                if start_loss is not None:
                    start_losses.append(start_loss)
                    final_losses.append(final_loss)
                    total_accepted += run_accepted
                    if run_accepted > 0:
                        improving_runs += 1
            except Exception as e:
                print(f"Error reading {path}: {e}")
                
        if completed_runs == 0:
            print(f"No completed runs found for domain: {d}")
            continue
            
        avg_start = np.mean(start_losses) if start_losses else float('inf')
        best_final = np.min(final_losses) if final_losses else float('inf')
        
        # Calculate mean and std of final losses (filter out inf)
        valid_finals = [l for l in final_losses if not np.isinf(l)]
        if valid_finals:
            mean_final = np.mean(valid_finals)
            std_final = np.std(valid_finals)
        else:
            mean_final = float('inf')
            std_final = 0.0
            
        is_real = d.startswith("real_")
        clean_name = d.replace("real_", "").replace("_", " ").title()
        if d == "real_co2":
            clean_name = r"Atmospheric $\text{CO}_2$"
        elif d == "real_macro":
            clean_name = "US Real GDP"
        elif d == "real_nile":
            clean_name = "Nile River Volume"
        elif d == "real_sunspots":
            clean_name = "Solar Sunspots"
        elif d == "real_theophylline":
            clean_name = "Oral Theophylline"
        elif d == "bz_chem":
            clean_name = "Belousov-Zhabotinsky"
        elif d == "pkpd":
            clean_name = "PK/PD"
            
        type_str = "Real-World" if is_real else "Synthetic"
        
        rows.append({
            "name": clean_name,
            "type": type_str,
            "avg_start": avg_start,
            "best_final": best_final,
            "mean_final": mean_final,
            "std_final": std_final,
            "improving_runs": improving_runs,
            "completed_runs": completed_runs,
            "total_accepted": total_accepted
        })
        
    # Generate LaTeX table
    tex_path = "paper/results_table.tex"
    with open(tex_path, "w") as f:
        f.write(r"% Generated by compile_paper_results.py. Do not edit manually." + "\n")
        f.write(r"\begin{table*}[t]" + "\n")
        f.write(r"\centering" + "\n")
        f.write(r"\caption{Performance Comparison and Discovery Metrics of SBI-Factory across Synthetic and Real-World domains.}" + "\n")
        f.write(r"\label{tab:results}" + "\n")
        f.write(r"\begin{tabular}{llccccr}" + "\n")
        f.write(r"\toprule" + "\n")
        f.write(r"Domain & Type & Starting MSE & Best Final MSE & Mean Final MSE & Imp. Runs & Accepted Mut.\\" + "\n")
        f.write(r"\midrule" + "\n")
        
        # Write Synthetic
        f.write(r"\multicolumn{7}{l}{\textbf{Synthetic Domains}} \\" + "\n")
        for r in rows:
            if r["type"] == "Synthetic":
                mean_str = f"{format_loss(r['mean_final'])} \\pm {r['std_final']:.4f}" if not np.isinf(r['mean_final']) else r"\infty"
                f.write(f"{r['name']} & {r['type']} & ${format_loss(r['avg_start'])}$ & ${format_loss(r['best_final'])}$ & ${mean_str}$ & {r['improving_runs']}/{r['completed_runs']} & {r['total_accepted']} \\\\\n")
                
        f.write(r"\midrule" + "\n")
        
        # Write Real-World
        f.write(r"\multicolumn{7}{l}{\textbf{Real-World Domains}} \\" + "\n")
        for r in rows:
            if r["type"] == "Real-World":
                mean_str = f"{format_loss(r['mean_final'])} \\pm {r['std_final']:.4f}" if not np.isinf(r['mean_final']) else r"\infty"
                f.write(f"{r['name']} & {r['type']} & ${format_loss(r['avg_start'])}$ & ${format_loss(r['best_final'])}$ & ${mean_str}$ & {r['improving_runs']}/{r['completed_runs']} & {r['total_accepted']} \\\\\n")
                
        f.write(r"\bottomrule" + "\n")
        f.write(r"\end{tabular}" + "\n")
        f.write(r"\end{table*}" + "\n")
        
    print(f"Successfully compiled results and wrote to {tex_path}")

if __name__ == "__main__":
    main()
